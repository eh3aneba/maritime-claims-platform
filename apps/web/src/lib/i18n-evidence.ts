const evidenceCatalog = { en: evidenceEn, fa: evidenceFa } as const;

export function evidenceT(locale: Locale, key: EvidenceKey, values?: Record<string, string | number>): string {
  let text: string = evidenceCatalog[locale][key] ?? evidenceEn[key];
  if (!values) return text;
  for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
