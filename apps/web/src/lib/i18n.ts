export const catalogs: Record<Locale, Record<TranslationKey, string>> = { en, fa };

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "fa";
}

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>): string {
  let text = catalogs[locale][key] ?? en[key];
  if (!values) return text;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
