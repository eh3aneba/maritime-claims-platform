export type AssessmentKey = keyof typeof en;

export function assessmentT(locale: Locale, key: AssessmentKey, values?: Record<string, string | number>) {
  let text = (locale === "fa" ? fa : en)[key];
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
